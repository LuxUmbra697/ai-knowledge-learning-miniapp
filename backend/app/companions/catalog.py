def character(identity):
    if identity not in CATALOG:
        raise ValueError('Unknown companion')
    return {key: deepcopy(value) for key, value in CATALOG[identity].items() if key != 'chapters'}


def story(identity, turns):
    character(identity)
    return [{'id': f'{identity}-{i + 1}', 'title': title, 'text': text, 'threshold': threshold}
            for i, (title, threshold, text) in enumerate(CATALOG[identity]['chapters']) if turns >= threshold]


def story_progress(identity, turns):
    return [{'id': f'{identity}-{i + 1}', 'title': title, 'threshold': threshold, 'unlocked': turns >= threshold}
            for i, (title, threshold, _text) in enumerate(CATALOG[identity]['chapters'])]
