"""Run a bounded, credential-free synthetic fitting/calibration experiment and save raw results."""
import argparse
import csv
import hashlib
import json
import platform
import sys
import time
from datetime import datetime, timezone
from pathlib import Path

import numpy as np

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / 'backend'))
from app.learning.bkt_experiment import (
    TRUTH,
    VERSION,
    calibrate,
    fit,
    metrics,
    paired_bootstrap,
    predict,
    rescale,
    simulate,
    split_learners,
)
from app.learning.knowledge_tracing import DEFAULT


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--output', type=Path, default=ROOT / 'eval/learning')
    parser.add_argument('--seed', type=int, default=20260915)
    parser.add_argument('--learners', type=int, default=800)
    args = parser.parse_args()
    started = time.perf_counter()
    data = simulate(args.learners, 30, args.seed)
    split = split_learners(len(data), args.seed + 1)
    train, validation, test = (data[split[key]] for key in ('train', 'validation', 'test'))
    fitted, trace = fit(train, seed=args.seed + 2)
    calibration = calibrate(predict(validation, fitted), validation)
    baseline = float(train.mean())
    predictions = {
        'constant_train_rate': np.full_like(test, baseline, dtype=float),
        'default_bkt': predict(test, DEFAULT),
        'fitted_bkt': predict(test, fitted),
        'calibrated_bkt': rescale(predict(test, fitted), calibration['temperature'], calibration['bias']),
    }
    partitions = {int(learner): name for name, ids in split.items() for learner in ids}
    rows = [{'learner_id': f'synthetic-{i:04d}', 'split': partitions[i], 'observations': data[i].tolist()} for i in range(len(data))]
    dataset = '\n'.join(json.dumps(row, sort_keys=True, separators=(',', ':')) for row in rows) + '\n'
    report = {'version': VERSION, 'data_source': 'Synthetic BKT simulator; no real learner records', 'seed': args.seed,
                  'recorded_at': datetime.now(timezone.utc).isoformat(),
                  'numpy_version': np.__version__, 'python_version': platform.python_version(),
                  'dataset_sha256': hashlib.sha256(dataset.encode()).hexdigest(),
                  'learners': len(data), 'attempts_per_learner': 30, 'split': {key: len(ids) for key, ids in split.items()},
                  'split_unit': 'learner, never individual observations', 'simulation_parameters': TRUTH,
                  'default_parameters': DEFAULT, 'fitted_parameters': fitted, 'calibration': calibration,
                  'fit': {'method': 'bounded random search plus coordinate refinement', 'candidates': 256, 'trace': trace},
                  'test_metrics': {name: metrics(test, values) for name, values in predictions.items()},
                  'paired_bootstrap': paired_bootstrap(test, predictions['default_bkt'], predictions['calibrated_bkt'], args.seed + 3),
                  'elapsed_seconds': round(time.perf_counter() - started, 4), 'provider_calls': 0,
                  'limitations': ['Synthetic data generated by the same model family favors BKT',
                               'No real-user benefit, retention improvement or personally trained parameters demonstrated',
                               'One skill, no forgetting, binary observations, no item difficulty or causal intervention',
                               'ECE depends on binning; calibration chosen only on validation, test untouched',
                               'Production runtime defaults are unchanged']}
    args.output.mkdir(parents=True, exist_ok=True)
    (args.output / 'dataset-v1.jsonl').write_text(dataset, encoding='utf-8', newline='\n')
    (args.output / 'results-v1.json').write_text(json.dumps(report, indent=2) + '\n', encoding='utf-8', newline='\n')
    with (args.output / 'predictions-v1.csv').open('w', newline='', encoding='utf-8') as stream:
        writer = csv.writer(stream, lineterminator='\n')
        writer.writerow(['learner_id', 'step', 'observed', *predictions])
        for index, learner in enumerate(split['test']):
            for step in range(test.shape[1]):
                writer.writerow([f'synthetic-{learner:04d}', step + 1, int(test[index, step]),
                                 *[f'{values[index, step]:.10f}' for values in predictions.values()]])
    print(json.dumps({key: report[key] for key in ('version', 'dataset_sha256', 'split', 'fitted_parameters', 'calibration', 'elapsed_seconds', 'provider_calls')}, indent=2))
    for name, result in report['test_metrics'].items():
        print(name, json.dumps({key: result[key] for key in ('log_loss', 'brier', 'ece_10')}))


if __name__ == '__main__':
    main()
